// UI translation lookup with fallback
export function t(lang, key) {
  const dictionary = UI_TRANSLATIONS[lang] || UI_TRANSLATIONS.eng_Latn;
  if (dictionary && dictionary[key]) {
    return dictionary[key];
  }
  if (UI_TRANSLATIONS.eng_Latn && UI_TRANSLATIONS.eng_Latn[key]) {
    return UI_TRANSLATIONS.eng_Latn[key];
  }
  return key;
}

// Translate answer body texts into target language
export function translateAnswerText(lang, text) {
  if (!text || lang === 'eng_Latn') return text;
  const langDict = CONSTITUTIONAL_TRANSLATIONS[lang];
  if (!langDict) return text;

  const trimmed = text.trim();
  if (langDict[trimmed]) return langDict[trimmed];

  // Try normalized whitespace match
  const normalized = trimmed.replace(/\s+/g, ' ');
  for (const [enKey, translatedVal] of Object.entries(langDict)) {
    if (enKey.replace(/\s+/g, ' ') === normalized) {
      return translatedVal;
    }
  }

  // Try sentence-by-sentence and substring replacement for constitutional phrases
  let result = text;
  for (const [enKey, translatedVal] of Object.entries(langDict)) {
    if (result.includes(enKey)) {
      result = result.replaceAll(enKey, translatedVal);
    }
  }

  // Common constitutional nomenclature localization
  if (lang === 'guj_Gujr') {
    result = result.replace(/\bArticle\s+(\d+[A-Za-z]*)\b/gi, 'કલમ $1');
    result = result.replace(/\bPart\s+([IVXLCDM]+)\b/gi, 'ભાગ $1');
    result = result.replace(/\bFundamental Rights\b/gi, 'મૂળભૂત અધિકારો');
    result = result.replace(/\bFundamental Duties\b/gi, 'મૂળભૂત ફરજો');
    result = result.replace(/\bConstitution of India\b/gi, 'ભારતનું બંધારણ');
    result = result.replace(/\bSupreme Court\b/gi, 'સર્વોચ્ચ અદાલત');
    result = result.replace(/\bHigh Court\b/gi, 'વડી અદાલત');
  } else if (lang === 'hin_Deva') {
    result = result.replace(/\bArticle\s+(\d+[A-Za-z]*)\b/gi, 'अनुच्छेद $1');
    result = result.replace(/\bPart\s+([IVXLCDM]+)\b/gi, 'भाग $1');
    result = result.replace(/\bFundamental Rights\b/gi, 'मौलिक अधिकार');
    result = result.replace(/\bFundamental Duties\b/gi, 'मौलिक कर्तव्य');
    result = result.replace(/\bConstitution of India\b/gi, 'भारत का संविधान');
    result = result.replace(/\bSupreme Court\b/gi, 'उच्चतम न्यायालय');
    result = result.replace(/\bHigh Court\b/gi, 'उच्च न्यायालय');
  }

  return result;
}

// High-fidelity multilingual translation engine
export function translateTextRobust(text, sourceLang, targetLang) {
  if (!text || sourceLang === targetLang) return text;

  // 1. Reverse translation: Gujarati or Hindi to English
  if (targetLang === 'eng_Latn') {
    const srcDict = CONSTITUTIONAL_TRANSLATIONS[sourceLang];
    if (srcDict) {
      const trimmed = text.trim();
      for (const [enKey, localizedVal] of Object.entries(srcDict)) {
        if (localizedVal.trim() === trimmed || localizedVal.toLowerCase() === trimmed.toLowerCase()) {
          return enKey;
        }
      }
      // Substring check
      let revResult = text;
      const sortedEntries = Object.entries(srcDict).sort((a, b) => b[1].length - a[1].length);
      for (const [enKey, localizedVal] of sortedEntries) {
        if (localizedVal.length > 3 && revResult.includes(localizedVal)) {
          revResult = revResult.replaceAll(localizedVal, enKey);
        }
      }
      return revResult;
    }
  }

  // 2. Cross-translation: Gujarati <-> Hindi
  if (sourceLang === 'guj_Gujr' && targetLang === 'hin_Deva') {
    const guDict = CONSTITUTIONAL_TRANSLATIONS.guj_Gujr;
    const hiDict = CONSTITUTIONAL_TRANSLATIONS.hin_Deva;
    const trimmed = text.trim();
    for (const [enKey, guVal] of Object.entries(guDict)) {
      if (guVal.trim() === trimmed && hiDict[enKey]) {
        return hiDict[enKey];
      }
    }
  }
  if (sourceLang === 'hin_Deva' && targetLang === 'guj_Gujr') {
    const hiDict = CONSTITUTIONAL_TRANSLATIONS.hin_Deva;
    const guDict = CONSTITUTIONAL_TRANSLATIONS.guj_Gujr;
    const trimmed = text.trim();
    for (const [enKey, hiVal] of Object.entries(hiDict)) {
      if (hiVal.trim() === trimmed && guDict[enKey]) {
        return guDict[enKey];
      }
    }
  }

  // 3. English to Target Language
  return translateAnswerText(targetLang, text);
}
